package prac23.Ex2;

public interface Queue {
    // Контракт интерфейса:
    // - Очередь следует принципу FIFO.
    // - Методы выбрасывают исключения при некорректных операциях (например, удаление из пустой очереди).
    // - Элементы не могут быть null.

    // Предусловие: очередь не полна
    // Постусловие: элемент добавлен в конец очереди
    void enqueue(Object element);

    // Предусловие: очередь не пуста
    // Постусловие: возвращён первый элемент, очередь не изменена
    Object element();

    // Предусловие: очередь не пуста
    // Постусловие: первый элемент удалён и возвращён
    Object dequeue();

    // Предусловие: нет
    // Постусловие: возвращён текущий размер очереди
    int size();

    // Предусловие: нет
    // Постусловие: возвращён true, если очередь пуста
    boolean isEmpty();

    // Предусловие: нет
    // Постусловие: очередь пуста
    void clear();
}
